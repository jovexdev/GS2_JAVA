CREATE TABLE AEGIS_EQUIPE (
    id NUMBER(19) PRIMARY KEY,
    nome VARCHAR2(100 CHAR) NOT NULL
);

CREATE TABLE AEGIS_USUARIO (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfil VARCHAR2(12 CHAR) NOT NULL,
    email VARCHAR2(254 CHAR) NOT NULL,
    senha_hash VARCHAR2(255 CHAR) NOT NULL,
    CONSTRAINT AEGIS_USUARIO_EMAIL_UK UNIQUE (email),
    CONSTRAINT AEGIS_USUARIO_PERFIL_CK CHECK (perfil IN ('CIDADAO', 'EMPRESA', 'GESTOR', 'AGENTE'))
);

CREATE TABLE AEGIS_CIDADAO (
    usuario_id NUMBER(19) PRIMARY KEY REFERENCES AEGIS_USUARIO(id),
    nome VARCHAR2(120 CHAR) NOT NULL,
    cpf VARCHAR2(11 CHAR) NOT NULL UNIQUE,
    endereco VARCHAR2(250 CHAR) NOT NULL,
    ocupacao VARCHAR2(100 CHAR),
    telefone VARCHAR2(30 CHAR)
);

CREATE TABLE AEGIS_EMPRESA (
    usuario_id NUMBER(19) PRIMARY KEY REFERENCES AEGIS_USUARIO(id),
    razao_social VARCHAR2(120 CHAR) NOT NULL,
    nome_fantasia VARCHAR2(120 CHAR),
    cnpj VARCHAR2(14 CHAR) NOT NULL UNIQUE,
    atividade_economica VARCHAR2(150 CHAR),
    endereco VARCHAR2(250 CHAR) NOT NULL,
    responsavel VARCHAR2(120 CHAR) NOT NULL,
    telefone VARCHAR2(30 CHAR),
    caracteristicas_instalacoes VARCHAR2(500 CHAR)
);

CREATE TABLE AEGIS_GESTOR (
    usuario_id NUMBER(19) PRIMARY KEY REFERENCES AEGIS_USUARIO(id),
    nome VARCHAR2(120 CHAR) NOT NULL,
    identificacao_funcional VARCHAR2(40 CHAR) UNIQUE,
    setor VARCHAR2(120 CHAR)
);

CREATE TABLE AEGIS_AGENTE (
    usuario_id NUMBER(19) PRIMARY KEY REFERENCES AEGIS_USUARIO(id),
    nome VARCHAR2(120 CHAR) NOT NULL,
    identificacao_funcional VARCHAR2(40 CHAR) UNIQUE,
    equipe_id NUMBER(19) NOT NULL REFERENCES AEGIS_EQUIPE(id)
);

CREATE TABLE AEGIS_OCORRENCIA (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    autor_id NUMBER(19) NOT NULL REFERENCES AEGIS_USUARIO(id),
    descricao VARCHAR2(1000 CHAR) NOT NULL,
    localizacao VARCHAR2(250 CHAR) NOT NULL,
    agua_parada NUMBER(1),
    reservatorio_aberto NUMBER(1),
    materiais_expostos NUMBER(1),
    prioridade_preliminar VARCHAR2(10 CHAR),
    justificativa VARCHAR2(250 CHAR),
    criada_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT AEGIS_OCORRENCIA_PRIO_CK CHECK (prioridade_preliminar IN ('CRITICA', 'INSTAVEL', 'OK'))
);

CREATE INDEX AEGIS_OCORRENCIA_AUTOR_IDX ON AEGIS_OCORRENCIA(autor_id);

CREATE TABLE AEGIS_VISTORIA (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id NUMBER(19) NOT NULL REFERENCES AEGIS_OCORRENCIA(id),
    equipe_id NUMBER(19) REFERENCES AEGIS_EQUIPE(id),
    status VARCHAR2(10 CHAR) NOT NULL,
    prioridade VARCHAR2(10 CHAR),
    agendada_para TIMESTAMP,
    resultado VARCHAR2(1000 CHAR),
    versao NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT AEGIS_VISTORIA_OCORR_UK UNIQUE (ocorrencia_id),
    CONSTRAINT AEGIS_VISTORIA_AGENDA_UK UNIQUE (equipe_id, agendada_para),
    CONSTRAINT AEGIS_VISTORIA_STATUS_CK CHECK (status IN ('PENDENTE', 'AGENDADA', 'CONCLUIDA')),
    CONSTRAINT AEGIS_VISTORIA_PRIO_CK CHECK (prioridade IN ('CRITICA', 'INSTAVEL', 'OK'))
);

CREATE TABLE AEGIS_HISTORICO (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vistoria_id NUMBER(19) NOT NULL REFERENCES AEGIS_VISTORIA(id),
    autor_id NUMBER(19) NOT NULL REFERENCES AEGIS_USUARIO(id),
    acao VARCHAR2(20 CHAR) NOT NULL,
    detalhe VARCHAR2(1000 CHAR) NOT NULL,
    registrado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX AEGIS_HISTORICO_VIST_IDX ON AEGIS_HISTORICO(vistoria_id);

